/**
 * Categorias posibles de un arbitraje dentro de un partido.
 */
public enum CategoriaArbitro {
    /** Arbitro principal. */
    PRINCIPAL,
    /** Primer asistente. */
    ASISTENTE1,
    /** Segundo asistente. */
    ASISTENTE2,
    /** Cuarto arbitro. */
    CUARTO_ARBITRO,
    /** VAR principal. */
    VAR_PRINCIPAL,
    /** VAR asistente. */
    VAR_ASISTENTE

}
