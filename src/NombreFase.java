/**
 * Fases en las que se organiza el torneo, desde la fase de grupos
 * hasta la final.
 */
public enum NombreFase {
    /** Fase de grupos. */
    GRUPOS,
    /** Dieciseisavos de final. */
    DIECISEISAVOS,
    /** Octavos de final. */
    OCTAVOS,
    /** Cuartos de final. */
    CUARTOS,
    /** Semifinal. */
    SEMIFINAL,
    /** Final. */
    FINAL
}
